"""Tracked items and gold events for AMI series never used for extraction (new-dev and new-val, see PROTOCOL.md).

Same format and procedure as October's `ledger-engine/scripts/ami/specs.py`, read by its unchanged `build_chains.py`:
    objects = (id, label, phrase used in questions, allowed values or "number")
    events  = (meeting letter, object id, value, DECISIONS sentence number, kw regex choosing among the linked turns)

Rules, fixed before the first series was written and applied to every series (the AI assistant writes the lists, as in
October; no model output on these series existed when they were written):
1. Every DECISIONS sentence of the human abstract is read; a compound sentence gives one event per clause.
2. A clause is an event if it decides (a) whether a named component or feature is in the product
   (included | excluded), (b) a categorical choice for a named product attribute (material, curvature, shape, energy
   source, chip, colour scheme, button type, devices controlled, locator signal, screen type), or (c) the selling price
   or the production cost as a number of euros.
3. Not events: process and planning decisions (next steps, evaluation, negotiation, promotion, who does what), target
   markets and age groups, vague qualities (fancy, ergonomic, simple, user-friendly, corporate image or logo visible),
   placement of parts, the presence of standard controls every remote has (power, volume, channel, number or OK keys),
   reasons, and hedged or conditional clauses ("possibly", "if it does not cost too much").
4. Allowed values: the values decided in the series plus alternatives the same series' abstracts name. A categorical
   slot with fewer than two such values takes its alternatives from October's slot of the same kind (case material:
   plastic, rubber, wood; chip: simple chip, advanced chip; button material: soft rubber, hard plastic); a slot with no
   October counterpart and no named alternative is dropped.
5. A later meeting's decision restating a value is a CONFIRM event, as in October. `skip_changes` lists slots whose
   value changes inside one meeting (the change count would be ambiguous).
6. kw: the clause's key term, matched against the utterances the human summary links point to (October's resolver
   falls back to turns within 45 s of the links, then to the best word overlap in the meeting).
7. Written while the new-val lists were drafted, still before any model output on these series: a negative decision on
   a two-valued slot gives the other value, on a larger slot it is not an event; a clause giving several values for one
   slot at once (several product variants) drops that slot for the series, as do contradictory decisions about one
   slot within one meeting's abstract; value names follow the abstract's wording.
"""

